-- Initialize PostgreSQL with pgvector extension for Clinical Analytics Platform
-- This script sets up the vector database for AI/ML operations

-- Create database
CREATE DATABASE clinical_analytics;

-- Connect to the database
\c clinical_analytics;

-- Create user
CREATE USER clinical_user WITH PASSWORD 'clinical_password';
GRANT ALL PRIVILEGES ON DATABASE clinical_analytics TO clinical_user;

-- Install pgvector extension
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Create schema for vector operations
CREATE SCHEMA IF NOT EXISTS clinical_vectors;
GRANT ALL ON SCHEMA clinical_vectors TO clinical_user;

-- Create clinical records table
CREATE TABLE clinical_records (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    patient_id VARCHAR(50) NOT NULL,
    patient_age INTEGER,
    patient_gender VARCHAR(20),
    bmi DECIMAL(5,2),
    heart_rate INTEGER,
    systolic_bp DECIMAL(5,2),
    diastolic_bp DECIMAL(5,2),
    temperature DECIMAL(4,1),
    clinical_narrative TEXT,
    symptoms TEXT[],
    medications TEXT[],
    record_type VARCHAR(50),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Create vector embeddings table for semantic search
CREATE TABLE clinical_vectors.clinical_embeddings (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    content TEXT NOT NULL,
    metadata JSONB,
    embedding vector(384), -- 384 dimensions for all-MiniLM-L6-v2 model
    record_id UUID REFERENCES clinical_records(id),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Create indexes for performance
CREATE INDEX idx_clinical_records_patient_id ON clinical_records(patient_id);
CREATE INDEX idx_clinical_records_type ON clinical_records(record_type);
CREATE INDEX idx_clinical_records_created_at ON clinical_records(created_at);

-- Create HNSW index for vector similarity search
CREATE INDEX idx_clinical_embeddings_vector ON clinical_vectors.clinical_embeddings 
USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64);

CREATE INDEX idx_clinical_embeddings_metadata ON clinical_vectors.clinical_embeddings 
USING GIN (metadata);

-- Grant permissions
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO clinical_user;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA clinical_vectors TO clinical_user;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO clinical_user;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA clinical_vectors TO clinical_user;

