-- Create function for similarity search
CREATE OR REPLACE FUNCTION search_similar_cases(
    query_embedding vector(384),
    similarity_threshold float DEFAULT 0.8,
    max_results int DEFAULT 10
)
RETURNS TABLE (
    record_id UUID,
    content TEXT,
    metadata JSONB,
    similarity_score float
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        ce.record_id,
        ce.content,
        ce.metadata,
        1 - (ce.embedding <=> query_embedding) as similarity_score
    FROM clinical_vectors.clinical_embeddings ce
    WHERE 1 - (ce.embedding <=> query_embedding) > similarity_threshold
    ORDER BY ce.embedding <=> query_embedding
    LIMIT max_results;
END;
$$ LANGUAGE plpgsql;

-- Create function for clinical risk assessment
CREATE OR REPLACE FUNCTION calculate_population_risk(
    age_min int DEFAULT 0,
    age_max int DEFAULT 120
)
RETURNS TABLE (
    risk_category TEXT,
    patient_count BIGINT,
    avg_systolic_bp DECIMAL,
    avg_bmi DECIMAL
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        CASE 
            WHEN cr.patient_age < 40 THEN 'Low Risk'
            WHEN cr.patient_age BETWEEN 40 AND 65 THEN 'Moderate Risk'
            ELSE 'High Risk'
        END as risk_category,
        COUNT(*) as patient_count,
        AVG(cr.systolic_bp) as avg_systolic_bp,
        AVG(cr.bmi) as avg_bmi
    FROM clinical_records cr
    WHERE cr.patient_age BETWEEN age_min AND age_max
    GROUP BY risk_category
    ORDER BY risk_category;
END;
$$ LANGUAGE plpgsql;

-- Create materialized view for analytics
CREATE MATERIALIZED VIEW clinical_analytics_summary AS
SELECT 
    record_type,
    COUNT(*) as total_records,
    AVG(patient_age) as avg_age,
    AVG(bmi) as avg_bmi,
    AVG(systolic_bp) as avg_systolic_bp,
    COUNT(DISTINCT patient_id) as unique_patients
FROM clinical_records
GROUP BY record_type;

-- Create index on materialized view
CREATE INDEX idx_clinical_analytics_summary_type ON clinical_analytics_summary(record_type);

-- Grant permissions on functions and views
GRANT EXECUTE ON FUNCTION search_similar_cases(vector, float, int) TO clinical_user;
GRANT EXECUTE ON FUNCTION calculate_population_risk(int, int) TO clinical_user;
GRANT SELECT ON clinical_analytics_summary TO clinical_user;

-- Create trigger to refresh materialized view
CREATE OR REPLACE FUNCTION refresh_clinical_analytics()
RETURNS TRIGGER AS $$
BEGIN
    REFRESH MATERIALIZED VIEW clinical_analytics_summary;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_refresh_analytics
    AFTER INSERT OR UPDATE OR DELETE ON clinical_records
    FOR EACH STATEMENT
    EXECUTE FUNCTION refresh_clinical_analytics();

COMMIT;